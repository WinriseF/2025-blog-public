import assert from 'node:assert/strict'

export async function checkFeatures(page, fixture, passphrase) {
	const initialBody = await page.getByLabel('笔记正文', { exact: true }).inputValue()
	let embeddedRequests = 0
	await page.route('https://tracker.example.test/**', route => { embeddedRequests++; return route.abort() })
	await page.getByLabel('笔记正文', { exact: true }).fill(initialBody + '\n\n<img src="https://tracker.example.test/pixel" onerror="window.__unsafeNote=1"><script>window.__unsafeNote=1</script>\n[unsafe](javascript:alert(1)) [safe](https://example.test/)')
	await page.getByRole('button', { name: '预览', exact: true }).click()
	const preview = page.locator('[class*="preview"]')
	await preview.getByText('safe', { exact: true }).waitFor()
	assert.equal(await preview.locator('script,img,iframe,svg,style,[onclick],[onerror]').count(), 0)
	assert.equal(await preview.locator('a[href^="javascript:"]').count(), 0)
	assert.equal(await preview.getByText('safe', { exact: true }).getAttribute('rel'), 'noopener noreferrer')
	assert.equal(embeddedRequests, 0)
	assert.equal(await page.evaluate(() => window.__unsafeNote), undefined)
	await page.getByRole('button', { name: '编辑', exact: true }).click()
	await page.getByLabel('笔记正文', { exact: true }).fill(initialBody)
	await page.getByLabel('标签，以逗号分隔', { exact: true }).fill('验收,工作')
	await page.getByRole('button', { name: '收藏笔记', exact: true }).click()
	await page.getByRole('button', { name: '已加密保存', exact: true }).waitFor()
	await page.getByRole('button', { name: '我的收藏', exact: false }).click()
	await page.getByText('Docker 浏览器验收', { exact: true }).click()
	await page.getByRole('button', { name: '移到回收站', exact: true }).click()
	await page.getByRole('button', { name: '已加密保存', exact: true }).waitFor()
	await page.getByRole('button', { name: '回收站', exact: false }).click()
	await page.getByText('Docker 浏览器验收', { exact: true }).click()
	await page.getByRole('button', { name: '恢复', exact: true }).click()
	await page.getByRole('button', { name: '已加密保存', exact: true }).waitFor()
	await page.getByRole('button', { name: '访问与安全', exact: true }).click()
	await page.getByPlaceholder('例如：我的 AI 助手').fill('Synthetic reader')
	await page.getByRole('button', { name: '创建', exact: true }).click()
	const apiKey = await page.getByLabel('新创建的 API Key', { exact: true }).inputValue()
	const read = await fetch(fixture.url + '/api/stack/v1/sync?since=0', { headers: { 'X-Inkstack-Key': apiKey } })
	assert.equal(read.status, 200)
	assert.equal((await fetch(fixture.url + '/api/stack/v1/bootstrap', { headers: { 'X-Inkstack-Key': apiKey } })).status, 401)
	await page.getByRole('button', { name: '我已保存', exact: true }).click()
	page.once('dialog', dialog => dialog.accept())
	await page.getByRole('button', { name: '撤销 Synthetic reader', exact: true }).click()
	await page.getByText('还没有访问 Key。', { exact: true }).waitFor()
	assert.equal((await fetch(fixture.url + '/api/stack/v1/sync?since=0', { headers: { 'X-Inkstack-Key': apiKey } })).status, 401)
	await page.getByRole('button', { name: '加密设置', exact: true }).click()
	await page.getByRole('button', { name: '更改加密口令', exact: true }).click()
	const nextPassphrase = passphrase + ' updated'
	await page.locator('input[name=encryption-passphrase]').fill(nextPassphrase)
	await page.getByPlaceholder('再次输入加密口令').fill(nextPassphrase)
	await page.getByRole('button', { name: '生成恢复密钥', exact: true }).click()
	const recovery = await page.getByRole('textbox', { name: /^恢复密钥/ }).innerText()
	await page.getByRole('checkbox').check()
	await page.getByRole('button', { name: '更新加密设置', exact: true }).click()
	await page.getByText('加密口令与恢复密钥已更新。', { exact: true }).waitFor()
	await page.getByRole('button', { name: '关闭', exact: true }).click()
	await page.getByRole('button', { name: '锁定空间', exact: true }).first().click()
	await page.locator('input[name=encryption-passphrase]').fill(passphrase)
	await page.getByRole('button', { name: '解锁空间', exact: true }).click()
	await page.getByText('加密口令不正确，无法解锁。', { exact: true }).waitFor()
	await page.getByRole('button', { name: '忘记口令？使用恢复密钥', exact: true }).click()
	await page.locator('input[name=encryption-passphrase]').fill(recovery)
	await page.getByRole('button', { name: '解锁空间', exact: true }).click()
	await page.getByText('Docker 浏览器验收', { exact: true }).click()
	assert.equal(await page.getByLabel('笔记正文', { exact: true }).inputValue(), initialBody)
	assert.equal(await page.getByLabel('标签，以逗号分隔', { exact: true }).inputValue(), '验收,工作')
	console.log('PASS: sanitized preview, no embedded requests, favorites, trash restore, read-only Key/revocation, keyring change and recovery unlock')
	return nextPassphrase
}
